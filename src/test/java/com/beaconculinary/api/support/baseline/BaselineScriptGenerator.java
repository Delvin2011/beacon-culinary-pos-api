package com.beaconculinary.api.support.baseline;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.stream.Collectors;

/**
 * T0-7: writes a Flyway baseline migration (B{N}__baseline.sql) from the schema of a freshly migrated database.
 *
 * <p>Order: tables (columns with identity, computed columns and defaults), primary keys and unique
 * constraints, check constraints, foreign keys, indexes, the required reference data (hand-written, passed
 * in), views (each after the views it reads) and triggers. Views and triggers are their stored definitions,
 * each in its own batch. Constraints SQL Server named itself get deterministic names
 * ({@link SchemaCatalog#name}). No collation, filegroup or database name is written, so the script runs on
 * SQL Server and Azure SQL and every column takes the database's default collation, as the migrations do.
 *
 * <p>The output is reviewed by a person before it is committed (docs/2026-11-21-new-customer-database.md).
 */
public final class BaselineScriptGenerator {
    private BaselineScriptGenerator() {
    }

    public static String generate(SchemaCatalog catalog, int version, String requiredData) {
        var out = new StringBuilder();
        out.append("""
                -- T0-7: baseline at V%1$d for NEW customer databases (docs/2026-11-21-new-customer-database.md).
                --
                -- Generated by BaselineScriptGenerator from a database migrated through V1..V%1$d, then reviewed.
                -- Flyway applies it only to an empty database, and only when db/baseline is in its locations;
                -- databases with migration history (OptimumSCS, dev, test) never run it. Migrations after V%1$d
                -- apply on top as usual.
                --
                -- The schema equals V1..V%1$d (BaselineSchemaIntegrationTests compares them); the data is only the
                -- REQUIRED reference rows: no demo users, menu, stock or other seeds.
                --
                -- NEVER EDIT THIS FILE once a customer database has been built from it. Re-baseline by adding a new
                -- B<N>__baseline.sql.

                """.formatted(version));

        section(out, "Tables");
        for (var table : catalog.tables().values()) {
            out.append("CREATE TABLE [").append(table.name()).append("] (\n");
            var lines = new ArrayList<String>();
            for (var c : table.columns()) {
                var line = new StringBuilder("    [").append(c.name()).append("] ");
                if (c.computed() != null) {
                    line.append("AS ").append(c.computed()).append(c.persisted() ? " PERSISTED" : "")
                            .append(c.persisted() && !c.nullable() ? " NOT NULL" : "");
                } else {
                    line.append(c.type());
                    if (c.identitySeed() != null) {
                        line.append(" IDENTITY(").append(c.identitySeed()).append(", ").append(c.identityIncrement()).append(")");
                    }
                    line.append(c.nullable() ? " NULL" : " NOT NULL");
                    if (c.defaultConstraint() != null) {
                        line.append(" CONSTRAINT [").append(catalog.name(c.defaultConstraint().name())).append("] DEFAULT ")
                                .append(c.defaultConstraint().definition());
                    }
                }
                lines.add(line.toString());
            }
            out.append(String.join(",\n", lines)).append("\n);\n");
        }
        out.append("GO\n");

        section(out, "Primary keys and unique constraints");
        catalog.keys().stream().sorted(Comparator.comparing(SchemaCatalog.Key::table).thenComparing(k -> !k.primary())
                        .thenComparing(SchemaCatalog.Key::name))
                .forEach(k -> out.append("ALTER TABLE [").append(k.table()).append("] ADD CONSTRAINT [").append(catalog.name(k.name()))
                        .append(k.primary() ? "] PRIMARY KEY " : "] UNIQUE ").append(k.clustered() ? "CLUSTERED " : "NONCLUSTERED ")
                        .append(columns(k.columns())).append(";\n"));
        out.append("GO\n");

        section(out, "Check constraints");
        for (var c : catalog.checks()) {
            out.append("ALTER TABLE [").append(c.table()).append("] ADD CONSTRAINT [").append(catalog.name(c.name()))
                    .append("] CHECK ").append(c.definition()).append(";\n");
        }
        out.append("GO\n");

        section(out, "Foreign keys");
        for (var f : catalog.foreignKeys()) {
            out.append("ALTER TABLE [").append(f.table()).append("] ADD CONSTRAINT [").append(catalog.name(f.name()))
                    .append("] FOREIGN KEY ").append(bracketed(f.columns())).append(" REFERENCES [").append(f.referencedTable())
                    .append("] ").append(bracketed(f.referencedColumns()));
            if (!"NO_ACTION".equals(f.onDelete())) {
                out.append(" ON DELETE ").append(f.onDelete().replace('_', ' '));
            }
            if (!"NO_ACTION".equals(f.onUpdate())) {
                out.append(" ON UPDATE ").append(f.onUpdate().replace('_', ' '));
            }
            out.append(";\n");
        }
        out.append("GO\n");

        section(out, "Indexes");
        for (var i : catalog.indexes()) {
            out.append("CREATE ").append(i.unique() ? "UNIQUE " : "").append(i.clustered() ? "CLUSTERED " : "NONCLUSTERED ")
                    .append("INDEX [").append(i.name()).append("] ON [").append(i.table()).append("] ").append(columns(i.keyColumns()));
            if (!i.includedColumns().isEmpty()) {
                out.append(" INCLUDE ").append(bracketed(i.includedColumns()));
            }
            if (i.filter() != null) {
                out.append(" WHERE ").append(i.filter());
            }
            out.append(";\n");
        }
        out.append("GO\n");

        section(out, "Required reference data (hand-written: src/test/resources/baseline/required-data.sql)");
        out.append(requiredData.strip()).append("\nGO\n");

        section(out, "Views");
        // A batch of its own: a comment in a view's or trigger's batch becomes part of its stored definition.
        out.append("GO\n\n");
        for (var v : catalog.viewsInDependencyOrder()) {
            out.append(asCreate(v.definition())).append("\nGO\n\n");
        }

        section(out, "Triggers");
        out.append("GO\n\n");
        for (var t : catalog.triggers()) {
            out.append(asCreate(t.definition())).append("\nGO\n\n");
        }
        return out.toString().replace("\r\n", "\n").stripTrailing() + "\n";
    }

    /** A stored module definition as a CREATE statement: one last changed by ALTER VIEW or ALTER TRIGGER is
     * stored with that text, which would fail on a new database. */
    static String asCreate(String definition) {
        return definition.strip().replaceFirst("(?is)^((?:\\s|--[^\\n]*\\n|/\\*.*?\\*/)*)ALTER(\\s+(?:VIEW|TRIGGER)\\b)", "$1CREATE$2");
    }

    private static void section(StringBuilder out, String title) {
        out.append("\n-- ").append(title).append(" ").append("-".repeat(Math.max(3, 96 - title.length()))).append("\n\n");
    }

    private static String columns(java.util.List<SchemaCatalog.IndexColumn> columns) {
        return columns.stream().map(SchemaCatalog.IndexColumn::sql).collect(Collectors.joining(", ", "(", ")"));
    }

    private static String bracketed(java.util.List<String> names) {
        return names.stream().map(n -> "[" + n + "]").collect(Collectors.joining(", ", "(", ")"));
    }
}
